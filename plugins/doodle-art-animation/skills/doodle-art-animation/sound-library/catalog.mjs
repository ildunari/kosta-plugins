// catalog.mjs: write catalog.md, the table of every effect in sfxlib.js, from the effects' own meta. Usage:
//   node catalog.mjs            rewrite catalog.md
//   node catalog.mjs --check    exit 1 if catalog.md is out of date (CI runs this)
//   node catalog.mjs --page out.html   also write the listening page: one self-contained HTML file (the library
//                                      inlined into listen.template.html) where every effect plays in the browser
// It needs no browser: defining an effect only records its meta, and the options column is read from the
// effect's source (every o.<name> it uses, minus the ones all effects share).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(resolve(here, 'sfxlib.js'), 'utf8');
const box = {}; vm.runInNewContext(src, { globalThis: box, WeakMap, Math, Float32Array, Object, Array, Error, Number, String, JSON });
const L = box.SFXLIB;

// options per effect, from its source text
const SHARED = new Set(['g', 'seed', 'pan', 'pitch']);
const opts = {}, starts = [...src.matchAll(/\bdefine\(\s*'([A-Za-z]\w*)'/g)];
starts.forEach((m, i) => {
  const body = src.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : src.length);
  opts[m[1]] = [...new Set([...body.matchAll(/\bo\.([A-Za-z]\w*)/g)].map(x => x[1]))].filter(k => !SHARED.has(k));
});

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const styleName = { '3dlight': '3DLight', 'doodle-draw': 'Doodle Draw' };
const names = Object.keys(L.meta);
let out = `# Sound library catalog

Generated by \`node catalog.mjs\` from the meta of every effect in \`sfxlib.js\`; do not edit by hand.
${names.length} effects in ${Object.keys(L.families).length} families. Every effect also takes \`g\`, \`pan\`, \`seed\` and, where it has a pitch,
\`pitch\` (README.md explains them). "Length" is the default length in seconds. Hear them all on the listening page
(README.md says how to build it).

| Family | Effects | For 3DLight | For Doodle Draw |
|---|---:|---:|---:|
`;
for (const [id, f] of Object.entries(L.families)) {
  const n = names.filter(k => L.meta[k].family === id);
  out += `| [${f.name}](#${id}) | ${n.length} | ${n.filter(k => L.meta[k].styles.includes('3dlight')).length} | ${n.filter(k => L.meta[k].styles.includes('doodle-draw')).length} |\n`;
}
for (const [id, f] of Object.entries(L.families)) {
  const n = names.filter(k => L.meta[k].family === id).sort();
  out += `\n<a id="${id}"></a>\n## ${f.name}\n\n${f.desc}\n\n`;
  if (!n.length) { out += '_None yet._\n'; continue; }
  out += '| Effect | Styles | What it sounds like | Fits | Options | Length |\n|---|---|---|---|---|---:|\n';
  for (const k of n) {
    const m = L.meta[k];
    out += `| \`${k}\` | ${m.styles.map(s => styleName[s] || s).join(', ')} | ${esc(m.desc)} | ${esc(m.events).replace(/;\s*/g, '; ')} | ${opts[k]?.length ? opts[k].map(x => '`' + x + '`').join(' ') : ''} | ${m.dur} |\n`;
  }
}
const pi = process.argv.indexOf('--page');
if (pi > 0) {
  const page = readFileSync(resolve(here, 'listen.template.html'), 'utf8')
    .replace('/*__SFXLIB__*/', () => src.replace(/<\/script/gi, '<\\/script'))
    .replace('/*__OPTS__*/{}', () => JSON.stringify(opts));
  writeFileSync(resolve(process.argv[pi + 1]), page); console.log('wrote ' + process.argv[pi + 1]);
}
const file = resolve(here, 'catalog.md');
if (process.argv.includes('--check')) {
  const old = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (old !== out) { console.error('catalog.md is out of date: run node catalog.mjs'); process.exit(1); }
  console.log(`catalog.md is up to date (${names.length} effects)`);
} else { writeFileSync(file, out); console.log(`wrote catalog.md (${names.length} effects)`); }
